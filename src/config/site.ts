function columns(items: readonly string[], count: number, width: number): string[] {
  const rows: string[] = []
  for (let i = 0; i < items.length; i += count) {
    rows.push(
      '  ' +
        items
          .slice(i, i + count)
          .map((item) => item.padEnd(width))
          .join('')
          .trimEnd(),
    )
  }
  return rows
}

